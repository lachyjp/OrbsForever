local checks = 0
local function check(ok, message) assert(ok, message); checks = checks + 1 end
combat = false
health, maxhealth, power, maxpower = 123, 456, 200, 800
O.Change("text", "combined")
O.Change("valueFormat", "both")
O.Change("fontSize", 24)
O.Change("valueFontSize", 16)
local h, p = O.orbs.health, O.orbs.power
check(h.value.format == "%.0f%%" and h.secondary.shown, "combined display contains both percentage and values")
check(h.secondary.args[1] == 123 and h.secondary.args[2] == 456, "health current and maximum displayed")
check(p.secondary.args[1] == 200 and p.secondary.args[2] == 800, "power current and maximum displayed")
check(h.value.fontSize == 24 and h.secondary.fontSize == 16, "independent font sizes")
O.Change("textOrder", "percentFirst")
check(h.value.point[3] > 0 and h.secondary.point[3] < 0, "percentage first")
O.Change("textOrder", "valueFirst")
check(h.value.point[3] < 0 and h.secondary.point[3] > 0, "values first")
O.Change("lineGap", 12)
check(h.value.point[3] == -14 and h.secondary.point[3] == 18, "line padding respects independently sized text")
O.Change("separatorPadding", 0)
check(h.secondary.format == "%s/%s", "zero separator padding")
O.Change("separatorPadding", 3)
check(h.secondary.format == "%s   /   %s", "equal padding on each side of slash")
O.Change("valueFormat", "current")
check(h.secondary.format == "%s" and h.secondary.args[1] == 123, "combined current-only option")
O.Change("text", "both")
check(not h.secondary.shown and h.value.format == "%s   /   %s" and h.value.fontSize == 16, "standalone pair uses value size and padding")
O.Change("text", "percent")
check(not h.secondary.shown and h.value.fontSize == 24, "percentage-only mode uses its own size")
O.Change("text", "none")
check(h.value.text == "" and not h.secondary.shown, "hidden mode hides both lines")
O.Change("text", "combined")
O.Change("valueFormat", "both")
health, maxhealth, power, maxpower = secret(), secret(), secret(), secret()
combat = true; O.Update()
check(issecretvalue(h.secondary.args[1]) and issecretvalue(h.secondary.args[2]), "restricted values formatted natively with padding")
O.Change("valueFontSize", 20)
check(h.secondary.fontSize == 16, "font change deferred during combat")
combat = false; fire("PLAYER_REGEN_ENABLED")
check(h.secondary.fontSize == 20, "queued value font size applied")
O.options.tabs.text.scripts.OnClick()
check(O.options.pages.text.shown and not O.options.pages.orb.shown and not O.options.pages.slots.shown, "Text section selection")
O.options.tabs.slots.scripts.OnClick()
check(O.options.pages.slots.shown and not O.options.pages.text.shown, "Slots section selection")
O.options.tabs.changes.scripts.OnClick()
check(O.options.pages.changes.shown and not O.options.resetSection.shown, "Changes page selection")
check(O.options.tabs.changes.text.text:find("|cffffd200%d+|r") ~= nil, "Changes tab counts changed settings")
OrbsUIOptionsSearch.text = "font edge"; OrbsUIOptionsSearch.scripts.OnTextChanged(OrbsUIOptionsSearch)
check(O.options.tabs.orb.alpha < 1 and O.options.tabs.text.alpha == 1, "search dims sections without matches")
OrbsUIOptionsSearch.text = ""; OrbsUIOptionsSearch.scripts.OnTextChanged(OrbsUIOptionsSearch)
local saved = {}
for _, f in ipairs(O.FIELDS) do if f.section == "text" then saved[f.key] = O.db[f.key] end end
O.options.tabs.text.scripts.OnClick()
O.options.resetSection.scripts.OnClick()
check(O.db.lineGap == 3 and O.db.text == "percent" and O.db.fontSize == 18 and O.db.healthLabel, "reset section restores text defaults")
for k, v in pairs(saved) do O.Change(k, v) end
O.options.tabs.orb.scripts.OnClick()
check(O.options.pages.orb.shown and not O.options.pages.slots.shown, "Orb section round trip")
return checks
